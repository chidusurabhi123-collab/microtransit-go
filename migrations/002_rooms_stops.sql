CREATE TABLE rooms (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  admin_token TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE stops (
  id SERIAL PRIMARY KEY,
  room_id TEXT REFERENCES rooms(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL,
  stop_order INT NOT NULL,
  dist_from_prev DOUBLE PRECISION DEFAULT 0,
  dist_to_final DOUBLE PRECISION DEFAULT 0
);
CREATE INDEX idx_stops_room_order ON stops(room_id, stop_order);
CREATE TABLE IF NOT EXISTS rooms(id TEXT PRIMARY KEY, name TEXT NOT NULL, admin_token TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS stops(id SERIAL PRIMARY KEY, room_id TEXT REFERENCES rooms(id) ON DELETE CASCADE, name TEXT, lat DOUBLE PRECISION, lng DOUBLE PRECISION, stop_order INT, dist_from_prev DOUBLE PRECISION DEFAULT 0, dist_to_final DOUBLE PRECISION DEFAULT 0);